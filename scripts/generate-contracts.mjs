import fs from 'node:fs/promises'
import path from 'node:path'
import {spawnSync} from 'node:child_process'
import openapiTS, {astToString} from 'openapi-typescript'
const root = path.resolve(import.meta.dirname, '..')
const python = process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python'
const result = spawnSync(python, ['-m', 'scripts.export-openapi'], {cwd: root, stdio:'inherit', windowsHide:true})
if (result.status !== 0) process.exit(result.status ?? 1)
const schema = JSON.parse(await fs.readFile(path.join(root,'.tmp/openapi.json'),'utf8'))
const manifest = JSON.parse(await fs.readFile(path.join(root,'.tmp/contract-manifest.json'),'utf8'))
const generated = astToString(await openapiTS(schema))
const target = path.join(root,'src/frontend/src/contracts')
const contents = new Map([['openapi.generated.ts', '// Generated by npm run contracts:generate. Do not edit.\n'+generated]])
let aliases = '// Generated from Pydantic response models. Do not edit.\nimport type { components } from \'./openapi.generated\'\n'
aliases += `export const API_CONTRACT_VERSION = '${manifest.version}' as const\n`
aliases += `export const CONTRACT_SYNC_TYPES = ${JSON.stringify(Object.values(manifest.models))} as const\n`
for (const [model, alias] of Object.entries(manifest.models)) aliases += `export type ${alias} = components['schemas']['${model}']\n`
aliases += 'export type BackendState = BackendStateResponse\nexport type Suggestion = SuggestionResponse\nexport type GraphIndexStatus = GraphIndexStatusResponse\n'
contents.set('apiContracts.ts', aliases)
for (const [name, content] of contents) {
  const file = path.join(target, name)
  if (process.argv.includes('--check')) {
    const previous = await fs.readFile(file, 'utf8').catch(() => '')
    if (previous.replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n')) throw new Error(`Contract drift: run npm run contracts:generate (${name})`)
  } else await fs.writeFile(file, content)
}
